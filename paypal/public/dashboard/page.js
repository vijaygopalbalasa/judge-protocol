// The jobs dashboard: public job views shown in AG Grid, with headline totals and a detail panel. It reads the sample
// file by default, or ?src= (an https address or this site) for live data. Every value is shown as text.
import { toRows, summarize } from "./rows.js";

const $ = (id) => document.getElementById(id);
const { agGrid } = globalThis;

async function load() {
  let url = new URL("./sample-jobs.json", location.href);
  let label = "Example data generated by the Judge engine. These are not real PayPal records.";
  const src = new URLSearchParams(location.search).get("src");
  if (src) {
    const u = new URL(src, location.href);
    if (u.protocol !== "https:" && u.origin !== location.origin) throw new Error("?src= must be an https address or this site");
    url = u;
    label = `Jobs from ${u.host}.`;
  }
  const res = await fetch(url, { credentials: "omit" });
  if (!res.ok) throw new Error(`could not load ${url.href}: HTTP ${res.status}`);
  return { views: await res.json(), label };
}

const money = (value, currency) => (value ? `${value} ${currency ?? ""}`.trim() : "");
const when = (iso) => (iso ? new Date(iso).toISOString().slice(0, 16).replace("T", " ") + " UTC" : "");

function kpis(s) {
  const items = [
    [s.jobs, "jobs"],
    [money(s.paidOut, s.currency) || "0.00", "paid out to workers"],
    [s.paid, "paid"],
    [s.refunded, "refunded"],
    [s.open, "open"],
    [s.needsAttention, "need attention"],
    [s.judged ? `${Math.round((s.passed / s.judged) * 100)}%` : "none yet", "of judged work passed"],
  ];
  $("kpis").replaceChildren(...items.map(([n, l]) => {
    const div = document.createElement("div");
    div.className = "kpi";
    const big = document.createElement("div");
    big.className = "n";
    big.textContent = String(n);
    const small = document.createElement("div");
    small.className = "l";
    small.textContent = l;
    div.append(big, small);
    return div;
  }));
}

function detail(row, view) {
  $("layout").classList.add("with-detail");
  $("detail").hidden = false;
  $("detail-title").textContent = row.title ?? row.id;
  const facts = [
    ["Job", row.id], ["Status", row.statusLabel], ["Price", money(row.price, row.currency)], ["Worker gets", money(row.payout, row.currency)],
    ["Result", row.result ? `${row.result}, score ${row.score}` : "not judged yet"], ["Checks", row.checks || "none run yet"],
    ["Criteria hash", row.criteriaHash], ["Evidence hash", row.evidenceHash ?? ""],
    ["PayPal order", row.orderId ?? ""], ["Capture", row.captureId ?? ""], ["Payout batch", row.payoutBatchId ?? ""],
    ["Deadline", when(row.deadline)],
  ];
  $("detail-facts").replaceChildren(...facts.flatMap(([k, v]) => {
    const dt = document.createElement("dt");
    dt.textContent = k;
    const dd = document.createElement("dd");
    dd.textContent = v ?? "";
    return [dt, dd];
  }));
  $("detail-criteria").textContent = JSON.stringify(view?.criteria ?? null, null, 2);
  const events = Array.isArray(view?.events) ? view.events : [];
  $("detail-events").replaceChildren(...events.map((e) => {
    const li = document.createElement("li");
    li.className = e.type === "failed" ? "bad" : "ok";
    li.textContent = `${when(e.at)}: ${e.type}${e.detail ? `, ${e.detail}` : ""}`;
    return li;
  }));
}

try {
  const { views, label } = await load();
  const rows = toRows(views);
  const byId = new Map(views.map((v) => [v?.id, v]));
  $("source").textContent = label;
  if (!rows.length) {
    const a = document.createElement("a");
    a.href = "/";
    a.textContent = "Create the first job";
    $("source").append(" No jobs yet on this server (a fresh demo instance starts empty). ", a, ", or view the ");
    const s = document.createElement("a");
    s.href = "./";
    s.textContent = "labelled example data";
    $("source").append(s, ".");
  }
  kpis(summarize(rows));
  if (agGrid.ModuleRegistry && agGrid.AllCommunityModule) agGrid.ModuleRegistry.registerModules([agGrid.AllCommunityModule]);
  agGrid.createGrid($("grid"), {
    rowData: rows,
    domLayout: "autoHeight",
    getRowId: (p) => p.data.id,
    defaultColDef: { sortable: true, filter: true, resizable: true, minWidth: 110 },
    columnDefs: [
      { field: "id", headerName: "Job", pinned: "left", width: 170 },
      { field: "title", headerName: "Work", flex: 2, minWidth: 220 },
      { field: "statusLabel", headerName: "Status", minWidth: 230,
        cellClassRules: { "st-paid": (p) => p.data.status === "paid", "st-refunded": (p) => p.data.status === "refunded",
          "st-attention": (p) => p.data.status === "failed" || p.data.underReview } },
      { field: "price", headerName: "Price", type: "rightAligned", width: 120, valueFormatter: (p) => money(p.value, p.data.currency) },
      { field: "payout", headerName: "Worker gets", type: "rightAligned", width: 130, valueFormatter: (p) => money(p.value, p.data.currency) },
      { field: "score", headerName: "Score", type: "rightAligned", width: 100, filter: "agNumberColumnFilter" },
      { field: "result", headerName: "Result", width: 110,
        cellClassRules: { "res-pass": (p) => p.value === "PASS", "res-reject": (p) => p.value === "REJECT" } },
      { field: "checks", headerName: "Checks", flex: 2, minWidth: 220 },
      { field: "orderId", headerName: "PayPal order", minWidth: 170 },
      { field: "captureId", headerName: "Capture", minWidth: 170 },
      { field: "payoutBatchId", headerName: "Payout batch", minWidth: 160 },
      { field: "updatedAt", headerName: "Updated", minWidth: 170, sort: "desc", valueFormatter: (p) => when(p.value) },
    ],
    onRowClicked: (e) => detail(e.data, byId.get(e.data.id)),
  });
} catch (err) {
  $("source").textContent = `Could not show the jobs: ${err.message}`;
}
